# Applied with --set-stages, and only to subsystems that have no stage yet.
DEMO_STAGES: dict[str, SubsystemStage] = {
    "battery": SubsystemStage.TESTING,
    "chassis": SubsystemStage.MANUFACTURING,
    "dynamics": SubsystemStage.REVIEW,
    "electrical": SubsystemStage.DESIGN,
    "shell": SubsystemStage.MANUFACTURING,
    "solar": SubsystemStage.TESTING,
    "strategy": SubsystemStage.DESIGN,
    "bizops": SubsystemStage.CONCEPT,
}


class DemoDataExistsError(Exception):
    pass


def seed_demo_data(
    db: Session,
    box: BoxService,
    xrpl: XrplClient,
    *,
    root_folder_id: str,
    vehicle: str,
    author: SessionUser,
    set_stages: bool = False,
    force: bool = False,
    log: Callable[[str], None] = print,
) -> list[CdxCommit]:
    if not force and db.scalar(select(func.count(CdxCommit.id))):
        raise DemoDataExistsError(
            "CDX already has commits; pass --force to add demo commits anyway"
        )

    layout = ensure_vehicle_layout(box, root_folder_id, vehicle)
    seeded = []
    for demo in DEMO_COMMITS:
        folders = layout[demo.subsystem]
        cdx_commit = create_cdx_commit(
            db,
            box,
            folder_id=folders.cad_folder_id if demo.in_cad_folder else folders.folder_id,
            file=CommitFile(demo.file_name, demo.content),
            message=demo.message,
            author=author,
            design_review=CommitFile(*demo.design_review) if demo.design_review else None,
        )
        cdx_commit = anchor_cdx_commit(db, xrpl, cdx_commit.id)
        log(
            f"{demo.subsystem:>10}  {demo.file_name:<34} {cdx_commit.anchor_status:<8} "
            f"{cdx_commit.xrpl_tx_hash or cdx_commit.anchor_error or ''}"
        )
        seeded.append(cdx_commit)

    if set_stages:
        staged = {row.slug for row in db.scalars(select(SubsystemMetadata)) if row.stage}
        for slug, stage in DEMO_STAGES.items():
            if slug not in staged:
                update_subsystem(db, slug, SubsystemUpdate(stage=stage), author)
    return seeded


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("vehicle", help="Vehicle folder to create/use under the Dashboard root")
    parser.add_argument("--author", help="Name shown on the commits (default: the Box account)")
    parser.add_argument("--set-stages", action="store_true", help="Fill in unset design stages")
    parser.add_argument("--force", action="store_true", help="Seed even if commits already exist")
    args = parser.parse_args()

    run_migrations()
    box, xrpl = get_box_service(), get_xrpl_client()
    if not xrpl.is_configured:
        print("XRPL anchoring isn't configured — commits will stay pending until it is.")
    author = box.get_current_user()
    if args.author:
        author = author.model_copy(update={"name": args.author})

    with get_sessionmaker()() as db:
        try:
            seeded = seed_demo_data(
                db,
                box,
                xrpl,
                root_folder_id=get_settings().require_dashboard_root_folder_id(),
                vehicle=args.vehicle,
                author=author,
                set_stages=args.set_stages,
                force=args.force,
            )
        except DemoDataExistsError as exc:
            raise SystemExit(str(exc)) from exc
    print(f"Seeded {len(seeded)} CDX commits.")


if __name__ == "__main__":
    main()
