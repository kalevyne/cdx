DEMO_HEADER = "Sample data generated by the CDX demo seed script (scripts/seed_demo_data.py)."


def _csv(header: str, rows: list[tuple]) -> bytes:
    lines = [f"# {DEMO_HEADER}", header, *(",".join(str(v) for v in row) for row in rows)]
    return ("\n".join(lines) + "\n").encode()


def _markdown(title: str, *paragraphs: str) -> bytes:
    return "\n\n".join([f"<!-- {DEMO_HEADER} -->", f"# {title}", *paragraphs, ""]).encode()


