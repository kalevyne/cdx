"""Seed a believable commit history for demos — through the real pipeline.

    python -m scripts.seed_demo_data "<Vehicle name>" [--author "Name"] [--set-stages]

Creates the vehicle's folder layout, then commits one or two small sample files
per subsystem exactly as an engineer would: uploaded to real Box, hashed, and
anchored to XRPL Testnet (synchronously, so the output shows each transaction).
Nothing is faked or backdated — timestamps are real, so run this a few days
before a demo, or re-run it (with --force) to add more history over time.

Every sample file says in its first line that it is demo data, so it's easy to
find and delete from Box afterwards. `--set-stages` also fills in a design stage
for subsystems that don't have one yet; leads are never invented.
"""

